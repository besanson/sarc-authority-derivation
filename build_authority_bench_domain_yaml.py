def _yaml_safe(value: Any) -> Any:
    """v1/v2's `consumed_grant_ids` is a frozenset-valued candidate
    property (`participation._serialize`'s own long-standing reason for
    existing, `authority_bench.py`'s own identical fix for JSON) --
    converted to a sorted list here too, recursively, only at the YAML
    boundary."""
    if isinstance(value, frozenset):
        return sorted(_yaml_safe(v) for v in value)
    if isinstance(value, (list, tuple)):
        return [_yaml_safe(v) for v in value]
    if isinstance(value, dict):
        return {k: _yaml_safe(v) for k, v in value.items()}
    return value


def _write_yaml(path: Path, data: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(_yaml_safe(data), sort_keys=False, default_flow_style=False))


