def build() -> None:
    domains = [
        ("v2", _candidate_context_v2, LOSS_MODEL_V2, REACHABILITY_V2, BASELINE_MANUAL_POLICY_V2, _expected_certificates_v2),
        ("v4", _candidate_context_v4, LOSS_MODEL_V4, REACHABILITY_V4, BASELINE_MANUAL_POLICY_V4, _expected_certificates_v4),
        ("data-and-communications", _candidate_context_datacomms, LOSS_MODEL_DATACOMMS, REACHABILITY_DATACOMMS, BASELINE_MANUAL_POLICY_DATACOMMS, _expected_certificates_datacomms),
    ]
    for name, candidate_context_fn, loss_model, reachability, manual_policy, expected_certificates_fn in domains:
        domain_dir = OUTPUT_ROOT / name
        _write_yaml(domain_dir / "candidate-context.yaml", candidate_context_fn())
        _write_yaml(domain_dir / "loss-model.yaml", loss_model)
        _write_yaml(domain_dir / "reachability.yaml", reachability)
        _write_yaml(domain_dir / "baseline-manual-policy.yaml", manual_policy)
        _write_yaml(domain_dir / "expected-certificates.yaml", expected_certificates_fn())
        print(f"wrote {domain_dir}/{{candidate-context,loss-model,reachability,baseline-manual-policy,expected-certificates}}.yaml")


if __name__ == "__main__":
    build()
